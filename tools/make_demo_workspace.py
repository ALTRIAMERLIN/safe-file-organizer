def content_for(rel: str, size: int) -> bytes:
    """Deterministic synthetic content."""
    if size == 0:
        return b""
    seed = f"SYNTHETIC DEMO DATA - not a real document - {rel}\n".encode("utf-8")
    return (seed * (size // len(seed) + 1))[:size]


def mtime_ns(iso: str) -> int:
    d = dt.datetime.fromisoformat(iso).replace(tzinfo=dt.timezone.utc)
    return int(d.timestamp()) * 1_000_000_000


def _write_files(dest: str, files) -> None:
    for rel, size, iso in files:
        p = os.path.join(dest, *rel.split("/"))
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "xb") as f:  # 'x': never overwrite
            f.write(content_for(rel, size))
        ns = mtime_ns(iso)
        os.utime(p, ns=(ns, ns))
    marker = os.path.join(dest, MARKER)
    with open(marker, "x", encoding="utf-8") as f:
        f.write("Synthetic demo fixture generated by make_demo_workspace.py. Safe to reset with --reset --yes.\n")
    if os.name == "nt":  # hidden, so the organizer's scanner skips it
        import ctypes
        ctypes.windll.kernel32.SetFileAttributesW(marker, 0x2)


def build(dest: str, files=DEMO_FILES) -> None:
    dest = os.path.abspath(dest)
    if os.path.exists(dest) and (not os.path.isdir(dest) or os.listdir(dest)):
        raise SystemExit(f"Refusing to write into non-empty path: {dest}. Use an empty or new folder.")
    os.makedirs(dest, exist_ok=True)
    _write_files(dest, files)


def reset(dest: str, files=DEMO_FILES) -> int:
    """Delete only manifest files (+ marker + resulting empty folders). Anything else makes it refuse."""
    dest = os.path.abspath(dest)
    if not os.path.isfile(os.path.join(dest, MARKER)):
        raise SystemExit("Not a generated demo workspace (marker missing). Nothing deleted.")
    removed = 0
    for rel, _s, _t in files:
        p = os.path.join(dest, *rel.split("/"))
        if os.path.isfile(p):
            os.remove(p)
            removed += 1
    os.remove(os.path.join(dest, MARKER))
    for rel, _s, _t in files:  # remove now-empty fixture folders only
        d = os.path.dirname(os.path.join(dest, *rel.split("/")))
        while os.path.abspath(d) != dest and os.path.isdir(d) and not os.listdir(d):
            os.rmdir(d)
            d = os.path.dirname(d)
    if os.path.isdir(dest) and not os.listdir(dest):
        os.rmdir(dest)
    return removed


def tree_snapshot(dest: str) -> dict[str, str]:
    """{relative path (/): sha256} of all files below dest, excluding the marker."""
    out = {}
    for base, _dirs, fs in os.walk(dest):
        for n in fs:
            p = os.path.join(base, n)
            rel = os.path.relpath(p, dest).replace("\\", "/")
            if rel == MARKER:
                continue
            with open(p, "rb") as f:
                out[rel] = hashlib.sha256(f.read()).hexdigest()
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("dest")
    ap.add_argument("--conflict", action="store_true", help="generate the conflict fixture instead")
    ap.add_argument("--reset", action="store_true")
    ap.add_argument("--yes", action="store_true")
    a = ap.parse_args(argv)
    files = CONFLICT_FILES if a.conflict else DEMO_FILES
    if a.reset:
        if not a.yes:
            raise SystemExit("--reset requires --yes. Only generated fixture files are removed.")
        print(f"Removed {reset(a.dest, files)} fixture files.")
    else:
        build(a.dest, files)
        print(f"Created {len(files)} synthetic files in {os.path.abspath(a.dest)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
